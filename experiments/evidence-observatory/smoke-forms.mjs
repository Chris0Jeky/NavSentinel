/** Viewer-only qualification of pinned, recorded synthetic form traces. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { gunzipSync } from 'node:zlib';
import { createHash } from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { chromium } from 'playwright';
import { buildReport, supportsCompleteSet } from './model.mjs';
import { writeReport } from './io.mjs';

assert.equal(process.argv.length, 2, 'This smoke uses only the checked-in synthetic sample.');
const root = fileURLToPath(new URL('./fixtures/forms/', import.meta.url));
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'provenance.json'), 'utf8'));
const packed = fs.readFileSync(path.join(root, 'recorded.json.gz'));
assert.equal(createHash('sha256').update(packed).digest('hex'), manifest.gzipSha256);
const raw = JSON.parse(gunzipSync(packed, { maxOutputLength: 1024 * 1024 }).toString('utf8'));
assert.equal(raw.length, 10);
for (const trace of raw) {
  assert.equal(trace.identity.head, manifest.producerHead);
  assert.equal(trace.identity.tree, manifest.producerTree);
}
const report = buildReport(raw.map(v => JSON.stringify(v)));
assert.equal(report.rejected.length, 0);
assert.equal(report.cases.length, 10);
assert.equal(supportsCompleteSet(report), false, 'paired form diagnostics never certify four-arm prevention');
const output = writeReport('test-results/observatory-form-viewer', report);
const errors = [], requests = [];
let browser;
try {
  browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
  await context.route('http://**/*', route => route.abort());
  await context.route('https://**/*', route => route.abort());
  const page = await context.newPage();
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => { if (/^https?:/.test(r.url())) requests.push(r.url()); });
  await page.goto(pathToFileURL(path.join(output, 'index.html')).href);
  await page.locator('.case-button').first().waitFor();
  const select = async (variant, arm) => {
    await page.locator('#search').fill(variant);
    await page.locator('#arm-filter').selectOption(arm);
    assert.equal(await page.locator('.case-button').count(), 1);
    await page.locator('.case-button').click();
    assert.equal(await page.locator('#form-panel table').count(), 0, 'no future form snapshot at run start');
    assert.equal(await page.locator('.receipt-link').count(), 0, 'no future receiver arrival at run start');
  };
  await select('action-substitution', 'protected');
  await page.getByRole('button', { name: 'Show input snapshot', exact: true }).click();
  assert.deepEqual(await page.locator('[data-field="action"] td').allTextContents(), ['benign', 'benign']);
  await page.getByRole('button', { name: 'Show operation snapshot', exact: true }).click();
  assert.deepEqual(await page.locator('[data-field="action"] td').allTextContents(), ['benign', 'harm']);
  assert.deepEqual(await page.locator('[data-field="submitter"] td').allTextContents(), ['a', 'none']);
  assert.ok(await page.locator('.form-changed').count() >= 3);
  await page.locator('#form-panel').screenshot({ path: path.join(output, 'action-substitution.png') });
  await page.getByRole('button', { name: 'Open baseline run', exact: true }).click();
  assert.match(await page.locator('#case-subtitle').innerText(), /baseline/);
  await page.locator('.event').last().click();
  assert.equal(await page.locator('.receipt-link').count(), 1);
  assert.match(await page.locator('#verdict').innerText(), /HARM OBSERVED/);
  assert.equal(await page.locator('#form-panel table').count(), 0, 'old intent not carried across navigation');
  await select('alternate-submitter', 'protected');
  await page.getByRole('button', { name: 'Show operation snapshot', exact: true }).click();
  assert.deepEqual(await page.locator('[data-field="submitter"] td').allTextContents(), ['a', 'b']);
  assert.deepEqual(await page.locator('[data-field="target"] td').allTextContents(), ['self', 'top']);
  await page.locator('#form-panel').screenshot({ path: path.join(output, 'alternate-submitter.png') });
  await select('late-submit', 'protected');
  assert.match(await page.locator('#verdict').innerText(), /HARM THEN RECOVERY/);
  await page.getByRole('button', { name: 'Show late mutation snapshot', exact: true }).click();
  assert.deepEqual(await page.locator('[data-field="action"] td').allTextContents(), ['benign', 'harm']);
  await page.locator('#form-panel').screenshot({ path: path.join(output, 'late-submit.png') });
  await page.locator('.event').last().click();
  assert.equal(await page.locator('.receipt-link').count(), 1);
  await page.locator('.receipt-link').click();
  assert.equal(await page.locator('#event-detail h3').innerText(), 'sink.receipt');
  await select('replay', 'baseline');
  await page.locator('.event').last().click();
  assert.match(await page.locator('#form-panel').innerText(), /Rejected receiver spends: 1/);
  await page.locator('.event').filter({ hasText: 'receiver.rejected' }).click();
  assert.match(await page.locator('#event-detail').innerText(), /not prevention by NavSentinel/);
  await select('mixed', 'mixed');
  const mixed = report.cases.find(c => c.variant === 'mixed');
  const freshSubmit = mixed.formEvidence.snapshots.findLast(v => v.phase === 'submit-event');
  await page.locator('.event').nth(freshSubmit.eventIndex).click();
  assert.deepEqual(await page.locator('[data-field="action"] td').allTextContents(), ['benign', 'benign'], 'fresh legitimate input is not paired with earlier attack input');
  await select('empty-target', 'benign');
  await page.getByRole('button', { name: 'Show input snapshot', exact: true }).click();
  assert.deepEqual(await page.locator('[data-field="targetOverride"] td').allTextContents(), ['empty', 'empty']);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true);
  await page.screenshot({ path: path.join(output, 'mobile.png'), fullPage: true });
  const downloadPromise = page.waitForEvent('download');
  await page.locator('#download').click();
  const file = path.join(output, 'download-checked.json');
  await (await downloadPromise).saveAs(file);
  assert.deepEqual(JSON.parse(fs.readFileSync(file, 'utf8')), report);
  assert.deepEqual(errors, []); assert.deepEqual(requests, []);
  console.log('Pinned recorded form viewer passed: overrides, alternative submitter, late mutation/recovery, rejected replay, temporal boundaries, mobile, JSON equality and zero HTTP requests. Not a new product campaign.');
} finally { await browser?.close(); }
